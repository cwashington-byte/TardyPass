package com.iar.tardypass.app

import android.app.Application
import android.content.Context
import com.iar.tardypass.BuildConfig
import com.iar.tardypass.data.local.AppDatabase
import com.iar.tardypass.data.remote.FirestoreSync
import com.iar.tardypass.data.repo.AuthRepository
import com.iar.tardypass.data.repo.PassRepository
import com.iar.tardypass.data.repo.SettingsRepository
import com.iar.tardypass.data.repo.StudentRepository
import com.iar.tardypass.printing.PrinterManager
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.launch
import kotlinx.coroutines.runBlocking

/** School's Google Workspace domain; blank disables the client-side check. */
const val SCHOOL_EMAIL_DOMAIN = "invictusofrichmond.org"

/** Manual DI — the whole graph is ~10 objects; Hilt isn't worth the startup cost here. */
class AppContainer(app: Application) {
    val appScope = CoroutineScope(SupervisorJob() + Dispatchers.Default)
    private val db = AppDatabase.build(app)
    val settings = SettingsRepository(app)
    val passes = PassRepository(db.passDao())
    val printer = PrinterManager(app, settings, appScope)

    /**
     * Read at runtime rather than as R.string.default_web_client_id: that
     * resource is generated by the google-services plugin, which is only
     * applied when google-services.json exists. Referencing it directly would
     * stop the project compiling before Firebase is configured.
     */
    private val webClientId: String = app.resolveStringResource("default_web_client_id")

    val auth = AuthRepository(
        appContext = app,
        webClientId = webClientId,
        hostedDomain = SCHOOL_EMAIL_DOMAIN
    )

    val sync = FirestoreSync(schoolId = { currentSchoolId })

    val students = StudentRepository(db.studentDao(), sync)

    /** Cached so Firestore paths don't need a suspend call on every access. */
    @Volatile
    private var currentSchoolId: String = com.iar.tardypass.data.repo.DEFAULT_SCHOOL_ID

    val pendingSharedCsv = MutableStateFlow<String?>(null)

    init {
        appScope.launch {
            currentSchoolId = settings.current().schoolId
            // Roster snapshots arrive on a Firestore thread; persist them here
            // where we own a scope.
            sync.onRosterSnapshot = { entities, syncedAt, authoritative ->
                appScope.launch {
                    // A server snapshot is the whole truth, so mirror it exactly —
                    // that's what makes a student deleted server-side disappear
                    // here too. A cache-only snapshot is additive: never prune.
                    if (authoritative) db.studentDao().reconcileRoster(entities, syncedAt)
                    else db.studentDao().upsertAll(entities)
                }
            }
            // Restore listeners for a session that persisted across app restarts,
            // and pick up access granted since the last launch.
            sync.onBellSchedule = { rawJson ->
                appScope.launch { settings.setBellScheduleJson(rawJson) }
            }
            auth.currentUser.value?.let { user ->
                if (BuildConfig.FIREBASE_CONFIGURED) {
                    sync.claimInviteIfPresent(user.uid, user.email, user.displayName)
                    sync.startRosterListener()
                    sync.startMemberListener(user.uid)
                    sync.startBellScheduleListener()
                }
            }
        }
        // Cache the role so the next cold start knows whether this is a shared
        // printer before Firestore answers. Only non-null: null conflates
        // "signed out" with "listener hasn't replied yet".
        appScope.launch {
            sync.memberRole.collect { role ->
                if (role != null) settings.setLastKnownRole(role)
            }
        }
    }
}

private fun Context.resolveStringResource(name: String): String {
    val id = resources.getIdentifier(name, "string", packageName)
    return if (id != 0) getString(id) else ""
}

class TardyPassApp : Application() {
    lateinit var container: AppContainer
        private set

    override fun onCreate() {
        super.onCreate()
        container = AppContainer(this)
        container.printer.startProbe()
    }
}
